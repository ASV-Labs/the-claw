import { SERVICE_LABELS } from "@/lib/services";
import type { Prize } from "@/lib/types";

type Draft = {
  id: string;
  name: string;
  glyph: string;
  group: keyof typeof SERVICE_LABELS;
  year: number;
  ended?: number;
  episodes: number;
  finished: boolean;
  genres: string[];
  intensity: 1 | 2 | 3 | 4 | 5;
  family?: boolean;
  background?: boolean;
  fumbledEnding?: boolean;
  blurb: string;
};

function entry(draft: Draft): Prize {
  const service = SERVICE_LABELS[draft.group];
  const span = draft.ended
    ? `${draft.year}, ran to ${draft.ended}`
    : `${draft.year}, still going`;
  const status = draft.finished
    ? draft.fumbledEnding
      ? "Finished, with an ending a lot of people argue about."
      : "Finished on its own terms."
    : "Still running, so you are signing up for more later.";
  const watch =
    draft.intensity <= 2
      ? "Easy to have on; not a dare."
      : draft.intensity >= 4
        ? "Asks for your full attention. Heavy, violent, or both."
        : "A proper watch, not wallpaper.";
  const family = draft.family
    ? "Fine with kids or parents in the room if you skip the odd joke."
    : "Made for adults.";
  const bg = draft.background
    ? "Works in the background."
    : "Needs you looking at the screen.";
  return {
    id: draft.id,
    name: draft.name,
    glyph: draft.glyph,
    group: draft.group,
    meta: `${service} · ${draft.year} · ${draft.episodes} eps`,
    facts: [
      `${draft.name} (${span}). ${draft.episodes} episodes. Streaming on ${service} in the US as of September 2026.`,
      `Genres: ${draft.genres.join(", ")}.`,
      draft.blurb,
      status,
      watch,
      family,
      bg,
    ].join(" "),
  };
}

